'use client';

import { useEffect, useState } from 'react';
import { AlertCircle, Download, Loader2, RefreshCw } from 'lucide-react';

import { Badge } from '@/components/ui/badge';
import { Button } from '@/components/ui/button';
import { fetchAuthedBlobUrl } from '@/lib/api-client';
import * as imageService from '@/services/image.service';
import type { GenerationResult } from '@/types/api';

const PROVIDER_LABEL: Record<string, string> = { openai: 'OpenAI', gemini: 'Gemini' };

interface ModelResultCardProps {
  slot: 1 | 2;
  result: GenerationResult;
  onRegenerate: (provider: GenerationResult['provider']) => void;
  regenerating: boolean;
}

/**
 * One provider's panel. Each card renders purely from its own result row, so a completed provider
 * displays immediately while its sibling is still pending, and a failed provider never hides the
 * successful one.
 */
export function ModelResultCard({ slot, result, onRegenerate, regenerating }: ModelResultCardProps) {
  const [imageSrc, setImageSrc] = useState<string | null>(null);
  const [imageError, setImageError] = useState(false);

  useEffect(() => {
    if (!result.image_url) {
      setImageSrc(null);
      return;
    }
    let revoked: string | null = null;
    let cancelled = false;

    void fetchAuthedBlobUrl(result.image_url)
      .then((url) => {
        if (cancelled) {
          URL.revokeObjectURL(url);
          return;
        }
        revoked = url;
        setImageSrc(url);
      })
      .catch(() => !cancelled && setImageError(true));

    return () => {
      cancelled = true;
      if (revoked) URL.revokeObjectURL(revoked);
    };
  }, [result.image_url]);

  const isLoading = result.status === 'pending' || result.status === 'processing';
  const isFailed = result.status === 'failed';

  const download = async () => {
    if (!result.image_url) return;
    await imageService.downloadImage(result.image_url, `${result.provider}-${result.id.slice(0, 8)}.png`);
  };

  return (
    <div className="flex flex-col overflow-hidden rounded-xl border bg-card">
      <div className="flex items-center justify-between border-b px-4 py-2.5">
        <div className="flex items-center gap-2">
          <span className="text-xs font-medium text-muted-foreground">Model {slot}</span>
          <span className="text-sm font-semibold">{PROVIDER_LABEL[result.provider] ?? result.provider}</span>
        </div>
        <StatusBadge status={result.status} />
      </div>

      <div className="relative flex aspect-square items-center justify-center bg-muted/40">
        {isLoading && (
          <div className="flex flex-col items-center gap-3 text-muted-foreground">
            <Loader2 className="h-6 w-6 animate-spin" />
            <p className="text-xs">Generating…</p>
          </div>
        )}

        {isFailed && (
          <div className="flex max-w-[85%] flex-col items-center gap-3 text-center">
            <AlertCircle className="h-6 w-6 text-destructive" />
            <p className="text-sm text-muted-foreground">{result.error ?? 'Generation failed.'}</p>
            <Button size="sm" variant="outline" className="gap-2" onClick={() => onRegenerate(result.provider)}>
              <RefreshCw className="h-3.5 w-3.5" />
              Retry
            </Button>
          </div>
        )}

        {result.status === 'completed' && imageSrc && (
          // eslint-disable-next-line @next/next/no-img-element -- authenticated blob: URL, not a static asset
          <img src={imageSrc} alt={`Generated by ${result.provider}`} className="h-full w-full object-contain" />
        )}

        {result.status === 'completed' && !imageSrc && !imageError && (
          <Loader2 className="h-5 w-5 animate-spin text-muted-foreground" />
        )}

        {imageError && <p className="text-sm text-muted-foreground">Could not load this image.</p>}
      </div>

      <div className="flex items-center gap-2 border-t px-4 py-3">
        <Button
          size="sm"
          variant="outline"
          className="flex-1 gap-2"
          disabled={result.status !== 'completed' || !imageSrc}
          onClick={() => void download()}
        >
          <Download className="h-3.5 w-3.5" />
          Download
        </Button>
        <Button
          size="sm"
          variant="ghost"
          className="flex-1 gap-2"
          disabled={isLoading || regenerating}
          onClick={() => onRegenerate(result.provider)}
        >
          <RefreshCw className={`h-3.5 w-3.5 ${regenerating ? 'animate-spin' : ''}`} />
          Regenerate
        </Button>
      </div>
    </div>
  );
}

function StatusBadge({ status }: { status: GenerationResult['status'] }) {
  if (status === 'completed') return <Badge variant="success">Done</Badge>;
  if (status === 'failed') return <Badge variant="destructive">Failed</Badge>;
  if (status === 'processing') return <Badge variant="warning">Generating</Badge>;
  return <Badge variant="secondary">Queued</Badge>;
}
